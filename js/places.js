// Drapeau émoji à partir du code ISO (indicateurs régionaux).
export function flagEmoji(iso) {
  if (!iso || iso.length !== 2) return '📍';
  const A = 0x1F1E6;
  return String.fromCodePoint(A + iso.charCodeAt(0) - 65, A + iso.charCodeAt(1) - 65);
}

// Normalisation pour la recherche : minuscules, sans accents ni tirets.
export function normalize(s) {
  return s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[’'\-]/g, ' ').replace(/\s+/g, ' ').trim();
}

// Recherche : préfixe de nom > début de mot > contenu. Renvoie au plus `max` entrées.
export function searchPlaces(query, max) {
  const q = normalize(query);
  if (!q) return [];
  const scored = [];
  for (const e of GAZETTEER) {
    const name = normalize(e.n);
    const extra = name + ' ' + (e.q || '') + ' ' + normalize(e.c || '');
    let score = -1;
    if (name.indexOf(q) === 0) score = 0;
    else if (extra.indexOf(' ' + q) !== -1 || (e.q && normalize(e.q).indexOf(q) === 0)) score = 1;
    else if (extra.indexOf(q) !== -1) score = 2;
    if (score >= 0) scored.push([score, e]);
  }
  scored.sort((a, b) => a[0] - b[0] || (a[1].n < b[1].n ? -1 : 1));
  return scored.slice(0, max || 8).map((s) => s[1]);
}
